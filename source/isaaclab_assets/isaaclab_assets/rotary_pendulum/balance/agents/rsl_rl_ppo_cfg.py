from isaaclab.utils import configclass

from isaaclab_rl.rsl_rl import RslRlOnPolicyRunnerCfg, RslRlPpoActorCriticCfg, RslRlPpoAlgorithmCfg


@configclass
class RotaryPendulumBalancePPORunnerCfg(RslRlOnPolicyRunnerCfg):
    num_steps_per_env = 10 * 60  # 600 steps per env per iteration
    max_iterations = 500
    save_interval = 100
    experiment_name = "rotary_pendulum_v2_balance"
    empirical_normalization = False

    policy = RslRlPpoActorCriticCfg(
        init_noise_std=0.5,
        actor_obs_normalization=True,
        critic_obs_normalization=True,
        # Smaller network for simpler 2-DOF problem
        actor_hidden_dims=[64, 128, 64],
        critic_hidden_dims=[64, 128, 64],
        activation="elu",
    )

    algorithm = RslRlPpoAlgorithmCfg(
        value_loss_coef=1.0,
        use_clipped_value_loss=True,
        clip_param=0.2,
        entropy_coef=0.01,
        num_learning_epochs=5,
        num_mini_batches=16,
        learning_rate=1e-3,
        schedule="adaptive",
        gamma=0.99,
        lam=0.95,
        desired_kl=0.01,
        max_grad_norm=1.0,
    )
